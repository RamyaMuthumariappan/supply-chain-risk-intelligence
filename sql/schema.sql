
CREATE TABLE IF NOT EXISTS public.orders (
    order_id BIGINT PRIMARY KEY,
    order_date DATE,
    shipping_mode VARCHAR(50),
    market VARCHAR(100),
    order_region VARCHAR(100),
    order_country VARCHAR(100),
    order_state VARCHAR(100),
    order_city VARCHAR(150),
    customer_segment VARCHAR(50),
    scheduled_days INTEGER,
    actual_shipping_days INTEGER,
    delivery_status VARCHAR(50),
    late_delivery_risk INTEGER,
    order_status VARCHAR(100),
    benefit_per_order NUMERIC(12,2),
    sales_per_customer NUMERIC(12,2),
    order_profit NUMERIC(12,2),
    item_count INTEGER,
    total_quantity INTEGER,
    total_sales NUMERIC(14,2),
    total_discount NUMERIC(14,2),
    total_order_item_value NUMERIC(14,2),
    average_discount_rate NUMERIC(8,4),
    unique_products INTEGER,
    unique_categories INTEGER,
    delay_days INTEGER,
    is_cancelled INTEGER,
    order_year INTEGER,
    order_month INTEGER,
    order_month_name VARCHAR(20),
    order_quarter INTEGER,
    order_day_of_week INTEGER,
    order_day_name VARCHAR(20),
    delivery_outcome VARCHAR(50)
);
